-- Exporta la ESTRUCTURA del esquema public (sin datos) como sentencias SQL, en el orden en que hay que ejecutarlas.
-- Sirve para crear la base de pruebas con la misma estructura que producción.
--
-- Uso: Supabase (proyecto de producción) → SQL Editor → pegar todo → Run → botón de exportar resultados a CSV.
--
-- No incluye los Database Webhooks (sus triggers guardan el secreto del header x-webhook-secret) ni datos.

with
cfg as (
  select 0 as grp, ''::text as obj, 'set check_function_bodies = off;'::text as sql
),
ext as (
  select 1, e.extname::text, format('create extension if not exists %I with schema %I;', e.extname, n.nspname)
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname <> 'plpgsql'
),
typ as (
  select 2, t.typname::text,
         format('create type public.%I as enum (%s);', t.typname,
                string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder))
  from pg_type t
  join pg_namespace n on n.oid = t.typnamespace
  join pg_enum e on e.enumtypid = t.oid
  where n.nspname = 'public'
  group by t.typname
),
seq as (
  -- Secuencias sueltas (serial). Las de columnas identity se crean solas con la tabla.
  select 3, c.relname::text, format('create sequence if not exists public.%I;', c.relname)
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'S'
    and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')
),
fn as (
  select 4, p.proname::text, pg_get_functiondef(p.oid) || ';'
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind in ('f', 'p')
    and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),
tbl as (
  select 5, c.relname::text,
         format(E'create table public.%I (\n%s\n);', c.relname,
                string_agg(format('  %I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                  case
                    when a.attidentity = 'a' then ' generated always as identity'
                    when a.attidentity = 'd' then ' generated by default as identity'
                    when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
                    when ad.adbin is not null then ' default ' || pg_get_expr(ad.adbin, ad.adrelid)
                    else ''
                  end,
                  case when a.attnotnull then ' not null' else '' end), E',\n' order by a.attnum))
  from pg_class c
  join pg_namespace n on n.oid = c.relnamespace
  join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef ad on ad.adrelid = c.oid and ad.adnum = a.attnum
  where n.nspname = 'public' and c.relkind in ('r', 'p')
  group by c.relname
),
con as (
  -- Primero claves primarias, únicas y checks (6); después las foráneas (7), que dependen de ellas.
  select case when co.contype = 'f' then 7 else 6 end, c.relname || '.' || co.conname,
         format('alter table public.%I add constraint %I %s;', c.relname, co.conname, pg_get_constraintdef(co.oid))
  from pg_constraint co
  join pg_class c on c.oid = co.conrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and co.contype in ('p', 'u', 'c', 'f', 'x')
),
idx as (
  select 8, i.relname::text, pg_get_indexdef(i.oid) || ';'
  from pg_index x
  join pg_class i on i.oid = x.indexrelid
  join pg_class c on c.oid = x.indrelid
  join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public'
    and not exists (select 1 from pg_constraint co
                    where co.conindid = i.oid and co.conrelid = c.oid and co.contype in ('p', 'u', 'x'))
),
vw as (
  select 9, c.relname::text, format(E'create or replace view public.%I as\n%s', c.relname, pg_get_viewdef(c.oid, true))
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'v'
),
rls as (
  select 10, c.relname::text, format('alter table public.%I enable row level security;', c.relname)
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind in ('r', 'p') and c.relrowsecurity
),
pol as (
  select 11, tablename || '.' || policyname,
         format('create policy %I on public.%I as %s for %s to %s%s%s;', policyname, tablename, permissive, cmd,
                array_to_string(roles::text[], ', '),
                case when qual is not null then ' using (' || qual || ')' else '' end,
                case when with_check is not null then ' with check (' || with_check || ')' else '' end)
  from pg_policies
  where schemaname = 'public'
),
trg as (
  select 12, t.tgname::text, pg_get_triggerdef(t.oid) || ';'
  from pg_trigger t
  join pg_class c on c.oid = t.tgrelid
  join pg_namespace n on n.oid = c.relnamespace
  join pg_proc p on p.oid = t.tgfoid
  join pg_namespace pn on pn.oid = p.pronamespace
  where n.nspname = 'public' and not t.tgisinternal
    and pn.nspname <> 'supabase_functions'  -- webhooks: llevan el secreto
)
select sql from (
  select * from cfg union all select * from ext union all select * from typ union all
  select * from seq union all select * from fn  union all select * from tbl union all
  select * from con union all select * from idx union all select * from vw  union all
  select * from rls union all select * from pol union all select * from trg
) todo
order by grp, obj;
